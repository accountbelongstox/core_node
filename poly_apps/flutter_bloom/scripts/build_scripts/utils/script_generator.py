"""
Script Generator for Flutter Build Process
Generates multiple independent PowerShell scripts for different build phases

REAL-TIME OUTPUT BEST PRACTICES
================================

PowerShell output can be buffered in various scenarios. To ensure real-time output:

✅ DO use these methods:
1. Direct execution in current process:
   Invoke-Expression "flutter build apk"

2. Calling scripts with & operator (in current process):
   & $scriptPath

3. Start-Transcript for logging (doesn't buffer console output):
   Start-Transcript -Path "log.txt"
   flutter build apk
   Stop-Transcript

❌ DON'T use these (they buffer output):
1. Tee-Object (buffers entire pipeline):
   flutter build apk | Tee-Object -FilePath "log.txt"

2. Starting new PowerShell process:
   & powershell -File $scriptPath
   powershell -Command "flutter build apk"

3. Redirecting to file (buffers output):
   flutter build apk > log.txt
   flutter build apk *>&1 | Out-File log.txt

IMPLEMENTATION PATTERN
======================

For real-time output + logging:

```powershell
try {
    # Start transcript for logging
    Start-Transcript -Path "build_log.txt" -Force | Out-Null

    # Execute command directly (real-time output)
    Invoke-Expression "flutter build apk --release"
    $exitCode = $LASTEXITCODE

    # Stop transcript
    Stop-Transcript | Out-Null
} catch {
    Stop-Transcript -ErrorAction SilentlyContinue | Out-Null
    $exitCode = 1
}
```

This ensures:
- Console output appears in real-time
- Full output is logged to file
- Exit codes are preserved
- Errors are handled gracefully
"""

