    def generate_all_scripts(self, cleanup_info: Dict[str, Any], comprehensive_paths: Dict[str, Any],
                           retry_paths: Dict[str, Any], flutter_command: str) -> Dict[str, str]:
        """Generate all script files and return their paths"""
        script_files = {}

        try:
            # Generate cleanup script
            cleanup_script_path = self.scripts_dir / "01_cleanup.ps1"
            cleanup_script_path.write_text(self.generate_cleanup_script(cleanup_info, comprehensive_paths), encoding='utf-8')
            script_files['cleanup_script'] = str(cleanup_script_path)

            # Generate Kotlin fix script
            kotlin_fix_script_path = self.scripts_dir / "02_kotlin_fix.ps1"
            kotlin_fix_script_path.write_text(self.generate_kotlin_fix_script(cleanup_info), encoding='utf-8')
            script_files['kotlin_fix_script'] = str(kotlin_fix_script_path)

            # Generate retry cleanup script
            retry_cleanup_script_path = self.scripts_dir / "03_retry_cleanup.ps1"
            retry_cleanup_script_path.write_text(self.generate_retry_cleanup_script(retry_paths, 1), encoding='utf-8')
            script_files['retry_cleanup_script'] = str(retry_cleanup_script_path)

            # Generate main build script
            build_script_path = self.scripts_dir / "04_build.ps1"
            build_script_path.write_text(self.generate_build_script(flutter_command), encoding='utf-8')
            script_files['build_script'] = str(build_script_path)

            # Generate main orchestrator script
            orchestrator_script_path = self.scripts_dir / "00_orchestrator.ps1"
            orchestrator_script_path.write_text(self.generate_main_orchestrator_script(script_files), encoding='utf-8')
            script_files['orchestrator_script'] = str(orchestrator_script_path)

            print(f"[ScriptGenerator] Successfully generated {len(script_files)} scripts")
            return script_files

        except Exception as e:
            print(f"[ScriptGenerator ERROR] Failed to generate scripts: {e}")
            import traceback
            traceback.print_exc()
            raise


