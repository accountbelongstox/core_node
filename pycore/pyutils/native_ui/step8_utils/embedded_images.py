def get_logo_image() -> Optional[Image.Image]:
    """
    Get the application logo as a PIL Image.
    
    Returns:
        PIL Image object, or None if loading fails
    """
    try:
        # Decode Base64
        img_data = base64.b64decode(LOGO_PNG_BASE64.strip())
        # Create PIL Image
        img = Image.open(io.BytesIO(img_data))
        return img
    except Exception as e:
        print(f"[EmbeddedImages] Failed to load logo: {e}")
        return None


def get_logo_bytes() -> Optional[bytes]:
    """
    Get the application logo as raw bytes.
    
    Returns:
        PNG bytes, or None if loading fails
    """
    try:
        return base64.b64decode(LOGO_PNG_BASE64.strip())
    except Exception as e:
        print(f"[EmbeddedImages] Failed to decode logo: {e}")
        return None
