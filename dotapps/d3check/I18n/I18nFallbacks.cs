    /// <summary>Fallback for dynamic skill key: ui.skill_table.skills.{skillKey}</summary>
    public static string GetSkillDisplayNameFallback(string skillKey, string languageCode)
    {
        if (string.Equals(languageCode, "zh", StringComparison.OrdinalIgnoreCase))
        {
            return skillKey switch
            {
                "skill1" => "技能一",
                "skill2" => "技能二",
                "skill3" => "技能三",
                "skill4" => "技能四",
                "left_click" => "左键",
                "right_click" => "右键",
                "potion" => "药水",
                _ => skillKey
            };
        }
        return skillKey switch
        {
            "skill1" => "Skill 1",
            "skill2" => "Skill 2",
            "skill3" => "Skill 3",
            "skill4" => "Skill 4",
            "left_click" => "Left Click",
            "right_click" => "Right Click",
            "potion" => "Potion",
            _ => skillKey
        };
    }
