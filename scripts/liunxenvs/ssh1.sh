    echo "[INFO] Executing: python -u '$sync_script' --target ssh --working-dir '$current_working_dir'"
    echo "[INFO] Working Directory: $current_working_dir"
    echo ""

    # Detect Python command
    if command -v python3 &> /dev/null; then
        PYTHON_CMD="python3"
    elif command -v python &> /dev/null; then
        PYTHON_CMD="python"
    else
        echo "[ERROR] Python not found"
        exit 1
    fi

    $PYTHON_CMD -u "$sync_script" --target ssh --working-dir "$current_working_dir"
else
    echo "[WARNING] MCP sync script not found: $sync_script"
    echo "[INFO] Skipping MCP synchronization"
fi

