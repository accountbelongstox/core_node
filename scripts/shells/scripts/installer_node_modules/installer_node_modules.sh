# Script identification and path setup
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
PACKAGE_JSON_PATH="$PROJECT_ROOT/package.json"
NODE_MODULES_PATH="$PROJECT_ROOT/node_modules"
YARN_LOCK_PATH="$PROJECT_ROOT/yarn.lock"

# Declare variables
FORCE_INSTALL=false
CHECK_ONLY=false
YARN_AVAILABLE=false
NPM_AVAILABLE=false

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Logging functions
log_info() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

log_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

log_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

# Parse command line arguments
parse_arguments() {
    while [[ $# -gt 0 ]]; do
        case $1 in
            --force)
                FORCE_INSTALL=true
                shift
                ;;
            --check-only)
                CHECK_ONLY=true
                shift
                ;;
            *)
                echo "Unknown option: $1"
                echo "Usage: $0 [--force] [--check-only]"
                exit 1
                ;;
        esac
    done
}

# Check if we're in the correct directory
check_project_root() {
    if [[ ! -f "$PACKAGE_JSON_PATH" ]]; then
        log_error "package.json not found at $PACKAGE_JSON_PATH"
        log_error "Please run this script from the project root or ensure the path is correct"
        exit 1
    fi
    
    log_info "Project root detected: $PROJECT_ROOT"
}

# Check if yarn is available
check_yarn_availability() {
    if command -v yarn >/dev/null 2>&1; then
        YARN_AVAILABLE=true
        local yarn_version=$(yarn --version 2>/dev/null)
        log_success "Yarn is available (version: $yarn_version)"
    else
        YARN_AVAILABLE=false
        log_warning "Yarn is not available"
    fi
}

# Check if npm is available
check_npm_availability() {
    if command -v npm >/dev/null 2>&1; then
        NPM_AVAILABLE=true
        local npm_version=$(npm --version 2>/dev/null)
        log_success "NPM is available (version: $npm_version)"
    else
        NPM_AVAILABLE=false
        log_error "NPM is not available"
    fi
}

# Install yarn if not available
install_yarn() {
    if [[ "$YARN_AVAILABLE" == true ]]; then
        log_info "Yarn is already available"
        return 0
    fi
    
    log_info "Installing Yarn..."
    
    if [[ "$NPM_AVAILABLE" == true ]]; then
        log_info "Installing Yarn via NPM..."
        if npm install -g yarn; then
            log_success "Yarn installed successfully via NPM"
            YARN_AVAILABLE=true
            return 0
        else
            log_error "Failed to install Yarn via NPM"
        fi
    fi
    
    # Try installing via package manager
    if command -v apt-get >/dev/null 2>&1; then
        log_info "Installing Yarn via apt-get..."
        if sudo apt-get update && sudo apt-get install -y yarn; then
            log_success "Yarn installed successfully via apt-get"
            YARN_AVAILABLE=true
            return 0
        else
            log_warning "Failed to install Yarn via apt-get"
        fi
    fi
    
    # Try installing via curl
    log_info "Installing Yarn via curl..."
    if curl -sS https://dl.yarnpkg.com/debian/pubkey.gpg | sudo apt-key add - && \
       echo "deb https://dl.yarnpkg.com/debian/ stable main" | sudo tee /etc/apt/sources.list.d/yarn.list && \
       sudo apt-get update && sudo apt-get install -y yarn; then
        log_success "Yarn installed successfully via curl"
        YARN_AVAILABLE=true
        return 0
    else
        log_error "Failed to install Yarn via curl"
        return 1
    fi
}

# Check if node_modules exists and is valid
check_node_modules() {
    if [[ ! -d "$NODE_MODULES_PATH" ]]; then
        log_warning "node_modules directory does not exist"
        return 1
    fi
    
    # Check if node_modules has content
    if [[ -z "$(ls -A "$NODE_MODULES_PATH" 2>/dev/null)" ]]; then
        log_warning "node_modules directory is empty"
        return 1
    fi
    
    log_success "node_modules directory exists and has content"
    return 0
}

# Install node modules
install_node_modules() {
    log_info "Installing node modules..."
    
    # Change to project root
    cd "$PROJECT_ROOT" || {
        log_error "Failed to change to project root directory"
        exit 1
    }
    
    # Prefer yarn if available, otherwise use npm
    if [[ "$YARN_AVAILABLE" == true ]]; then
        log_info "Using Yarn to install dependencies..."
        if yarn install; then
            log_success "Dependencies installed successfully with Yarn"
            return 0
        else
            log_error "Failed to install dependencies with Yarn"
            return 1
        fi
    elif [[ "$NPM_AVAILABLE" == true ]]; then
        log_info "Using NPM to install dependencies..."
        if npm install; then
            log_success "Dependencies installed successfully with NPM"
            return 0
        else
            log_error "Failed to install dependencies with NPM"
            return 1
        fi
    else
        log_error "Neither Yarn nor NPM is available"
        return 1
    fi
}

# Main function
main() {
    log_info "Node Modules and Yarn Installer Script"
    
    # Parse arguments
    parse_arguments "$@"
    
    # Check project root
    check_project_root
    
    # Check package manager availability
    check_npm_availability
    check_yarn_availability
    
    # If check-only mode, just report status and exit
    if [[ "$CHECK_ONLY" == true ]]; then
        log_info "Check-only mode enabled"
        
        if check_node_modules; then
            log_success "node_modules is properly installed"
        else
            log_warning "node_modules needs to be installed"
        fi
        
        if [[ "$YARN_AVAILABLE" == true ]]; then
            log_success "Yarn is available"
        else
            log_warning "Yarn is not available"
        fi
        
        exit 0
    fi
    
    # Install yarn if not available
    if [[ "$YARN_AVAILABLE" == false ]]; then
        if ! install_yarn; then
            log_error "Failed to install Yarn, will proceed with NPM if available"
        fi
    fi
    
    # Check if we need to install node_modules
    if [[ "$FORCE_INSTALL" == true ]] || ! check_node_modules; then
        if [[ "$FORCE_INSTALL" == true ]]; then
            log_info "Force install mode enabled"
        fi
        
        if ! install_node_modules; then
            log_error "Failed to install node modules"
            exit 1
        fi
    else
        log_success "node_modules is already properly installed"
    fi
    
    log_success "Node modules and Yarn setup completed successfully!"
}

# Run main function with all arguments
main "$@"
