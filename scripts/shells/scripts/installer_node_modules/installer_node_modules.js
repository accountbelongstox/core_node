'use strict';

const path = require('path');
const fs = require('fs');
const { spawn } = require('child_process');

// Declare variables
const scriptDir = __dirname;
const projectRoot = path.resolve(scriptDir, '../../../..');
const packageJsonPath = path.join(projectRoot, 'package.json');
const nodeModulesPath = path.join(projectRoot, 'node_modules');
const yarnLockPath = path.join(projectRoot, 'yarn.lock');

let forceInstall = false;
let checkOnly = false;
let yarnAvailable = false;
let npmAvailable = false;

// Colors for output
const colors = {
    red: '\x1b[31m',
    green: '\x1b[32m',
    yellow: '\x1b[33m',
    blue: '\x1b[34m',
    reset: '\x1b[0m'
};

// Logging functions
function logInfo(message) {
    console.log(`${colors.blue}[INFO]${colors.reset} ${message}`);
}

function logSuccess(message) {
    console.log(`${colors.green}[SUCCESS]${colors.reset} ${message}`);
}

function logWarning(message) {
    console.log(`${colors.yellow}[WARNING]${colors.reset} ${message}`);
}

function logError(message) {
    console.log(`${colors.red}[ERROR]${colors.reset} ${message}`);
}

// Parse command line arguments
function parseArguments() {
    const args = process.argv.slice(2);
    
    for (const arg of args) {
        switch (arg) {
            case '--force':
                forceInstall = true;
                break;
            case '--check-only':
                checkOnly = true;
                break;
            default:
                console.log(`Unknown option: ${arg}`);
                console.log('Usage: node installer_node_modules.js [--force] [--check-only]');
                process.exit(1);
        }
    }
}

// Check if we're in the correct directory
function checkProjectRoot() {
    if (!fs.existsSync(packageJsonPath)) {
        logError(`package.json not found at ${packageJsonPath}`);
        logError('Please run this script from the project root or ensure the path is correct');
        process.exit(1);
    }
    
    logInfo(`Project root detected: ${projectRoot}`);
}

// Execute command and return promise
function executeCommand(command, args = [], options = {}) {
    return new Promise((resolve, reject) => {
        const child = spawn(command, args, {
            stdio: 'pipe',
            ...options
        });
        
        let stdout = '';
        let stderr = '';
        
        child.stdout.on('data', (data) => {
            stdout += data.toString();
        });
        
        child.stderr.on('data', (data) => {
            stderr += data.toString();
        });
        
        child.on('close', (code) => {
            if (code === 0) {
                resolve({ stdout, stderr, code });
            } else {
                reject({ stdout, stderr, code });
            }
        });
        
        child.on('error', (error) => {
            reject({ error, stdout, stderr, code: -1 });
        });
    });
}

// Check if yarn is available
async function checkYarnAvailability() {
    try {
        const result = await executeCommand('yarn', ['--version']);
        yarnAvailable = true;
        logSuccess(`Yarn is available (version: ${result.stdout.trim()})`);
    } catch (error) {
        yarnAvailable = false;
        logWarning('Yarn is not available');
    }
}

// Check if npm is available
async function checkNpmAvailability() {
    try {
        const result = await executeCommand('npm', ['--version']);
        npmAvailable = true;
        logSuccess(`NPM is available (version: ${result.stdout.trim()})`);
    } catch (error) {
        npmAvailable = false;
        logError('NPM is not available');
    }
}

// Install yarn if not available
async function installYarn() {
    if (yarnAvailable) {
        logInfo('Yarn is already available');
        return true;
    }
    
    logInfo('Installing Yarn...');
    
    if (npmAvailable) {
        try {
            logInfo('Installing Yarn via NPM...');
            await executeCommand('npm', ['install', '-g', 'yarn']);
            logSuccess('Yarn installed successfully via NPM');
            yarnAvailable = true;
            return true;
        } catch (error) {
            logError('Failed to install Yarn via NPM');
        }
    }
    
    // Try installing via package manager (Linux)
    if (process.platform === 'linux') {
        try {
            logInfo('Installing Yarn via apt-get...');
            await executeCommand('sudo', ['apt-get', 'update']);
            await executeCommand('sudo', ['apt-get', 'install', '-y', 'yarn']);
            logSuccess('Yarn installed successfully via apt-get');
            yarnAvailable = true;
            return true;
        } catch (error) {
            logWarning('Failed to install Yarn via apt-get');
        }
    }
    
    logError('Failed to install Yarn');
    return false;
}

// Check if node_modules exists and is valid
function checkNodeModules() {
    if (!fs.existsSync(nodeModulesPath)) {
        logWarning('node_modules directory does not exist');
        return false;
    }
    
    // Check if node_modules has content
    try {
        const files = fs.readdirSync(nodeModulesPath);
        if (files.length === 0) {
            logWarning('node_modules directory is empty');
            return false;
        }
    } catch (error) {
        logWarning('Cannot read node_modules directory');
        return false;
    }
    
    logSuccess('node_modules directory exists and has content');
    return true;
}

// Install node modules
async function installNodeModules() {
    logInfo('Installing node modules...');
    
    // Change to project root
    process.chdir(projectRoot);
    
    // Prefer yarn if available, otherwise use npm
    if (yarnAvailable) {
        try {
            logInfo('Using Yarn to install dependencies...');
            await executeCommand('yarn', ['install'], { stdio: 'inherit' });
            logSuccess('Dependencies installed successfully with Yarn');
            return true;
        } catch (error) {
            logError('Failed to install dependencies with Yarn');
            return false;
        }
    } else if (npmAvailable) {
        try {
            logInfo('Using NPM to install dependencies...');
            await executeCommand('npm', ['install'], { stdio: 'inherit' });
            logSuccess('Dependencies installed successfully with NPM');
            return true;
        } catch (error) {
            logError('Failed to install dependencies with NPM');
            return false;
        }
    } else {
        logError('Neither Yarn nor NPM is available');
        return false;
    }
}

// Main function
async function main() {
    try {
        logInfo('Node Modules and Yarn Installer Script');
        
        // Parse arguments
        parseArguments();
        
        // Check project root
        checkProjectRoot();
        
        // Check package manager availability
        await checkNpmAvailability();
        await checkYarnAvailability();
        
        // If check-only mode, just report status and exit
        if (checkOnly) {
            logInfo('Check-only mode enabled');
            
            if (checkNodeModules()) {
                logSuccess('node_modules is properly installed');
            } else {
                logWarning('node_modules needs to be installed');
            }
            
            if (yarnAvailable) {
                logSuccess('Yarn is available');
            } else {
                logWarning('Yarn is not available');
            }
            
            process.exit(0);
        }
        
        // Install yarn if not available
        if (!yarnAvailable) {
            const yarnInstalled = await installYarn();
            if (!yarnInstalled) {
                logError('Failed to install Yarn, will proceed with NPM if available');
            }
        }
        
        // Check if we need to install node_modules
        if (forceInstall || !checkNodeModules()) {
            if (forceInstall) {
                logInfo('Force install mode enabled');
            }
            
            const installed = await installNodeModules();
            if (!installed) {
                logError('Failed to install node modules');
                process.exit(1);
            }
        } else {
            logSuccess('node_modules is already properly installed');
        }
        
        logSuccess('Node modules and Yarn setup completed successfully!');
        
    } catch (error) {
        logError(`Unexpected error: ${error.message}`);
        process.exit(1);
    }
}

// Export for use as module
module.exports = {
    main,
    checkNodeModules,
    checkYarnAvailability,
    checkNpmAvailability,
    installYarn,
    installNodeModules
};

// Run main function if this file is executed directly
if (require.main === module) {
    main();
}
