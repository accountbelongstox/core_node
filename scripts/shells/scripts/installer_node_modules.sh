# Script identification and path setup
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CORE_NODE_ROOT="$(dirname "$(dirname "$(dirname "$SCRIPT_DIR")")")"

# Declare variables
FORCE_INSTALL=false
CHECK_ONLY=false
NODE_MODULES_DIR="$CORE_NODE_ROOT/node_modules"
PACKAGE_JSON="$CORE_NODE_ROOT/package.json"
PNPM_LOCK="$CORE_NODE_ROOT/pnpm-lock.yaml"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Print functions
print_header() {
    echo -e "\n${BLUE}=== $1 ===${NC}"
    echo -e "${BLUE}==================================================${NC}\n"
}

print_step() {
    echo -e "${BLUE}>>> $1${NC}"
}

print_info() {
    echo -e "${BLUE}[INFO] $1${NC}"
}

print_success() {
    echo -e "${GREEN}[OK] $1${NC}"
}

print_warning() {
    echo -e "${YELLOW}[WARNING] $1${NC}"
}

print_error() {
    echo -e "${RED}[ERROR] $1${NC}"
}

# Parse command line arguments
parse_arguments() {
    while [[ $# -gt 0 ]]; do
        case $1 in
            --force)
                FORCE_INSTALL=true
                shift
                ;;
            --check)
                CHECK_ONLY=true
                shift
                ;;
            *)
                echo "Unknown option: $1"
                echo "Usage: $0 [--force] [--check]"
                exit 1
                ;;
        esac
    done
}

# Check if node_modules exists and is properly installed
check_node_modules() {
    print_step "Checking node_modules installation..."
    
    # Check if package.json exists
    if [[ ! -f "$PACKAGE_JSON" ]]; then
        print_error "package.json not found at $PACKAGE_JSON"
        return 1
    fi
    
    # Check if node_modules directory exists
    if [[ ! -d "$NODE_MODULES_DIR" ]]; then
        print_warning "node_modules directory not found"
        return 1
    fi
    
    # Check if node_modules has content
    if [[ -z "$(ls -A "$NODE_MODULES_DIR" 2>/dev/null)" ]]; then
        print_warning "node_modules directory is empty"
        return 1
    fi
    
    # Check if pnpm-lock.yaml exists (indicates pnpm was used)
    if [[ -f "$PNPM_LOCK" ]]; then
        print_info "pnpm-lock.yaml found, checking pnpm installation consistency..."

        # Check if pnpm is available
        if ! command -v pnpm >/dev/null 2>&1; then
            print_warning "pnpm-lock.yaml exists but pnpm command not found"
            return 1
        fi
        
        # Check if installation is up to date (simplified check)
        local package_json_time=$(stat -c %Y "$PACKAGE_JSON" 2>/dev/null || echo 0)
        local node_modules_time=$(stat -c %Y "$NODE_MODULES_DIR" 2>/dev/null || echo 0)
        
        if [[ $package_json_time -gt $node_modules_time ]]; then
            print_warning "package.json is newer than node_modules, may need reinstall"
            return 1
        fi
    fi
    
    print_success "node_modules appears to be properly installed"
    return 0
}

# Install node_modules using pnpm
install_node_modules() {
    print_step "Installing node_modules using pnpm..."

    # Check if pnpm is available
    if ! command -v pnpm >/dev/null 2>&1; then
        print_error "pnpm command not found. Please install pnpm first."
        print_info "You can install pnpm with: npm install -g pnpm"
        return 1
    fi
    
    # Change to core_node directory
    cd "$CORE_NODE_ROOT" || {
        print_error "Failed to change to core_node directory: $CORE_NODE_ROOT"
        return 1
    }
    
    print_info "Working directory: $(pwd)"
    print_info "Installing dependencies with pnpm..."

    # Run pnpm install
    if pnpm install; then
        print_success "pnpm install completed successfully"
        return 0
    else
        print_error "pnpm install failed"
        return 1
    fi
}

# Clean node_modules if needed
clean_node_modules() {
    if [[ -d "$NODE_MODULES_DIR" ]]; then
        print_step "Cleaning existing node_modules..."
        rm -rf "$NODE_MODULES_DIR"
        print_success "node_modules cleaned"
    fi
}

# Main installation function
main_install() {
    print_header "Node Modules Installation for core_node"
    
    print_info "Core Node Root: $CORE_NODE_ROOT"
    print_info "Package JSON: $PACKAGE_JSON"
    print_info "Node Modules: $NODE_MODULES_DIR"
    print_info "Force Install: $FORCE_INSTALL"
    print_info "Check Only: $CHECK_ONLY"
    
    # Check current status
    if check_node_modules; then
        if [[ "$FORCE_INSTALL" == true ]]; then
            print_info "Force install requested, proceeding with reinstallation..."
            clean_node_modules
        elif [[ "$CHECK_ONLY" == true ]]; then
            print_success "Check completed: node_modules is properly installed"
            return 0
        else
            print_success "node_modules is already properly installed"
            print_info "Use --force to reinstall or --check to only check status"
            return 0
        fi
    else
        if [[ "$CHECK_ONLY" == true ]]; then
            print_warning "Check completed: node_modules needs installation"
            return 1
        fi
        print_info "node_modules needs to be installed"
    fi
    
    # Install node_modules
    if install_node_modules; then
        print_success "Node modules installation completed successfully!"
        
        # Verify installation
        if check_node_modules; then
            print_success "Installation verification passed"
            return 0
        else
            print_warning "Installation completed but verification failed"
            return 1
        fi
    else
        print_error "Node modules installation failed"
        return 1
    fi
}

# Main script execution
main() {
    # Parse arguments
    parse_arguments "$@"
    
    # Check if we're in the right directory structure
    if [[ ! -f "$PACKAGE_JSON" ]]; then
        print_error "This script must be run from within the core_node project structure"
        print_error "Expected package.json at: $PACKAGE_JSON"
        exit 1
    fi
    
    # Run main installation
    main_install
    exit $?
}

# Run main function with all arguments
main "$@"
