<#
.SYNOPSIS
    Generate complete command content (advanced interface)

.DESCRIPTION
    This is the main interface for generating command content, integrating all necessary functionality

.PARAMETER Config
    Configuration object

.PARAMETER CommandPrefix
    Command prefix

.PARAMETER PsCommand
    PowerShell command

.PARAMETER FileNumber
    File number

.PARAMETER UserInputs
    User input environment variable values

.PARAMETER ShowPreview
    Whether to show preview (default: true)

.PARAMETER RequireConfirmation
    Whether to require user confirmation (default: true)

.EXAMPLE
    $result = New-CompleteCommandContent -Config $config -CommandPrefix "claude" -PsCommand "claude" -FileNumber 1 -UserInputs $inputs
#>
function New-CompleteCommandContent {
    param(
        [Parameter(Mandatory=$true)]
        [hashtable]$Config,

        [Parameter(Mandatory=$true)]
        [string]$CommandPrefix,

        [Parameter(Mandatory=$true)]
        [string]$PsCommand,

        [Parameter(Mandatory=$true)]
        [int]$FileNumber,

        [Parameter(Mandatory=$true)]
        [hashtable]$UserInputs,

        [Parameter(Mandatory=$false)]
        [bool]$ShowPreview = $true,

        [Parameter(Mandatory=$false)]
        [bool]$RequireConfirmation = $true,

        [Parameter(Mandatory=$false)]
        [string]$FileName = ""
    )

    try {
        $commandContent = $null
        $linuxContent = $null

        if ($CommandPrefix -eq "ssh") {
            $commandContent = New-SSHCommandContent -ConfigName $Config.Title -FileNumber $FileNumber -UserInputs $UserInputs -FileName $FileName
            $linuxContent = New-LinuxSSHCommandContent -ConfigName $Config.Title -FileNumber $FileNumber -UserInputs $UserInputs -FileName $FileName
        } else {
            $mcpSection = Get-McpSectionByToolType -ToolType $PsCommand -FileName $FileName
            $commandContent = New-CommandContent -ConfigName $Config.Title -CommandPrefix $CommandPrefix -PsCommand $PsCommand -FileNumber $FileNumber -Variables $Config.Variables -McpSection $mcpSection -FileName $FileName
            $linuxContent = New-LinuxCommandContent -ConfigName $Config.Title -CommandPrefix $CommandPrefix -PsCommand $PsCommand -FileNumber $FileNumber -Variables $Config.Variables -FileName $FileName
        }

        if ($ShowPreview) {
            $targetPath = Join-Path $Global:INLINE_WINENVS_DIR "${CommandPrefix}${FileNumber}.ps1"
            Show-CommandPreview -Content $commandContent -FilePath $targetPath
        }

        if ($RequireConfirmation) {
            $confirmed = Confirm-CommandGeneration
            if (-not $confirmed) {
                return @{
                    Success = $false
                    Message = "User cancelled command generation"
                    Content = $null
                    LinuxContent = $null
                }
            }
        }

        $linuxWriteSuccess = Write-LinuxScript -Content $linuxContent -CommandPrefix $CommandPrefix -FileNumber $FileNumber
        if ($linuxWriteSuccess) {
            Write-ColorMessage -Message "Linux script generated successfully for cross-platform compatibility" -Type "Success"
        } else {
            Write-ColorMessage -Message "Failed to generate Linux script, but Windows script will continue" -Type "Warning"
        }

        return @{
            Success = $true
            Message = "Command content generated successfully (Windows + Linux)"
            Content = $commandContent
            LinuxContent = $linuxContent
            McpSection = ""
        }

    } catch {
        return @{
            Success = $false
            Message = "Error occurred while generating command content: $($_.Exception.Message)"
            Content = $null
            LinuxContent = $null
        }
    }
}

<#
