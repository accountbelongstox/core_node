<#
.SYNOPSIS
    Generate generic MCP synchronization section for any AI tool

.DESCRIPTION
    Generate PowerShell content for any AI tool including pre-launch script, upgrade checks and MCP synchronization
    This is the core function that all tool-specific functions should use

.PARAMETER ToolType
    Tool type (e.g., "claude", "droid")

.PARAMETER ToolDisplayName
    Display name for the tool (e.g., "Claude Code", "Factory AI Droid")

.PARAMETER TargetName
    Target name for MCP sync (e.g., "claude", "droid")

.PARAMETER SupportUpgrade
    Whether the tool supports upgrade functionality (default: true)

.PARAMETER FileName
    The PowerShell file name that will be executed

.EXAMPLE
    $mcpContent = New-GenericMcpSection -ToolType "claude" -ToolDisplayName "Claude Code" -TargetName "claude" -SupportUpgrade $true
#>
function New-GenericMcpSection {
    param(
        [Parameter(Mandatory=$true)]
        [ValidateNotNullOrEmpty()]
        [string]$ToolType,

        [Parameter(Mandatory=$true)]
        [ValidateNotNullOrEmpty()]
        [string]$ToolDisplayName,

        [Parameter(Mandatory=$true)]
        [ValidateNotNullOrEmpty()]
        [string]$TargetName,

        [Parameter(Mandatory=$false)]
        [bool]$SupportUpgrade = $true,

        [Parameter(Mandatory=$false)]
        [string]$FileName = ""
    )

    try {
        $updateScriptPath = Get-UpdateScriptPath -ToolType $ToolType
        $syncScriptPath = Get-McpSyncScriptPath -ToolType $ToolType
        $preLaunchScriptPath = Get-PreLaunchScriptPath -ToolType $ToolType
    } catch {
        Write-Error "Failed to get script paths for tool type '${ToolType}': $($_.Exception.Message)"
        throw
    }

    $preLaunchSection = @"
# Execute pre-launch script if it exists
if (Test-Path "${preLaunchScriptPath}") {
    `$currentWorkingDir = Get-Location
    Write-Host "[INFO] Executing pre-launch script: ${preLaunchScriptPath}" -ForegroundColor Cyan
    Write-Host "[INFO] Working Directory: `$currentWorkingDir" -ForegroundColor Cyan
    Write-Host ""
    & "${preLaunchScriptPath}" -WorkingDirectory "`$currentWorkingDir"
    Write-Host ""
}
"@

    $upgradeSection = ""
    if ($SupportUpgrade) {
        $upgradeSection = @"

Write-Host "Available tasks:" -ForegroundColor White
Write-Host "  [1] Upgrade ${ToolDisplayName} to latest version (runs in separate window)" -ForegroundColor White
Write-Host "  [2] Sync MCP server configurations (runs now)" -ForegroundColor White
Write-Host ""

`$upgradeChoice = Read-Host "Do you want to upgrade ${ToolDisplayName}? (y/N)"
if (`$upgradeChoice -eq "y" -or `$upgradeChoice -eq "Y") {
    Write-Host ""
    Write-Host "[INFO] Launching ${ToolDisplayName} upgrade in separate window..." -ForegroundColor Yellow
    Start-Process -FilePath "${updateScriptPath}" -WindowStyle Normal
    Write-Host "[SUCCESS] Upgrade window opened" -ForegroundColor Green
} else {
    Write-Host "[INFO] Skipping upgrade" -ForegroundColor Cyan
}

"@
    }

    $syncSection = @"
`$currentWorkingDir = Get-Location
Write-Host ""
Write-Host "Syncing MCP Server Configurations..." -ForegroundColor Yellow
Write-Host ""
Write-Host "[INFO] Executing: python -u ```"${syncScriptPath}```" --target ${TargetName} --working-dir ```"`$currentWorkingDir```"" -ForegroundColor Cyan
Write-Host "[INFO] Working Directory: `$currentWorkingDir" -ForegroundColor Cyan
Write-Host ""

python -u "${syncScriptPath}" --target ${TargetName} --working-dir "`$currentWorkingDir"

Write-Host ""
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "Press Enter to start ${ToolDisplayName}..." -ForegroundColor Yellow
Write-Host "============================================================" -ForegroundColor Cyan
`$null = Read-Host "Press Enter to continue"
"@

    return @"
Write-Host "${ToolDisplayName} - Pre-Launch Tasks" -ForegroundColor Yellow
Write-Host ""

$preLaunchSection
$upgradeSection
$syncSection
"@
}

