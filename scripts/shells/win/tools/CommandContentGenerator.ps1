<#
.SYNOPSIS
    Generate complete batch command content

.DESCRIPTION
    Generate batch script content including environment variable setup, MCP synchronization, tool startup and other functionality based on configuration information

.PARAMETER ConfigName
    Configuration name (e.g. "Claude AI", "Factory AI Droid")

.PARAMETER CommandPrefix
    Command prefix (e.g. "claude", "droid")

.PARAMETER PsCommand
    PowerShell command (e.g. "claude", "droid")

.PARAMETER FileNumber
    File number (used to generate unique filename)

.PARAMETER EnvCommands
    Environment variable setup command array

.PARAMETER PsEnvVars
    PowerShell environment variable string

.PARAMETER McpSection
    MCP synchronization section content

.EXAMPLE
    $content = New-CommandContent -ConfigName "Claude AI" -CommandPrefix "claude" -PsCommand "claude" -FileNumber 1 -EnvCommands $envCmds -PsEnvVars $psVars -McpSection $mcp
#>
function New-CommandContent {
    param(
        [Parameter(Mandatory=$true)]
        [string]$ConfigName,
        
        [Parameter(Mandatory=$true)]
        [string]$CommandPrefix,
        
        [Parameter(Mandatory=$true)]
        [string]$PsCommand,
        
        [Parameter(Mandatory=$true)]
        [int]$FileNumber,
        
        [Parameter(Mandatory=$true)]
        [array]$EnvCommands,
        
        [Parameter(Mandatory=$true)]
        [string]$PsEnvVars,
        
        [Parameter(Mandatory=$false)]
        [string]$McpSection = ""
    )
    
    # Generate file header information
    $header = @"
@echo off
REM $ConfigName Global File #$FileNumber
REM Generated on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
REM 
REM This file is automatically generated by Special Software Environment Manager
REM Contains environment variable setup, MCP synchronization and tool startup functionality
REM 
REM Configuration Information:
REM   - Tool Name: $ConfigName
REM   - Command Prefix: $CommandPrefix
REM   - PowerShell Command: $PsCommand
REM   - File Number: $FileNumber
REM   - Generation Time: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
REM
"@

    # Generate environment variable setup section
    $envSection = @"

REM =============================================================================
REM Environment Variable Setup Section
REM =============================================================================
REM Set environment variables required for tool execution
REM These variables will remain valid throughout the batch script execution
REM
$($EnvCommands -join "`n")
REM
REM Environment variable setup completed
REM =============================================================================
"@

    # Generate MCP synchronization section (if provided)
    $mcpSectionContent = ""
    if (-not [string]::IsNullOrWhiteSpace($McpSection)) {
        $mcpSectionContent = @"

REM =============================================================================
REM MCP Server Synchronization Section
REM =============================================================================
REM Synchronize MCP server configurations to ensure tools can access the latest server settings
REM This section generates appropriate synchronization logic based on different tool types
REM
$McpSection
REM
REM MCP synchronization completed
REM =============================================================================
"@
    }

    # Generate tool startup section
    $launchSection = @"

REM =============================================================================
REM Tool Startup Section
REM =============================================================================
REM Launch target tool using configured environment variables
REM PowerShell command will inherit all set environment variables
REM
echo.
echo ============================================================
echo Starting $ConfigName
echo ============================================================
echo.
echo Executing command: $PsCommand
echo.
echo Complete PowerShell command: powershell -NoProfile -ExecutionPolicy Bypass -Command "$PsEnvVars; $PsCommand"
echo.
echo Press any key to continue execution...
pause >nul

REM Execute PowerShell command, passing all environment variables
powershell -NoProfile -ExecutionPolicy Bypass -Command "$PsEnvVars; $PsCommand"

REM Check execution result
if %ERRORLEVEL% EQU 0 (
    echo.
    echo [SUCCESS] $ConfigName started successfully
) else (
    echo.
    echo [ERROR] $ConfigName startup failed, exit code: %ERRORLEVEL%
)

echo.
echo ============================================================
echo Execution completed
echo ============================================================
pause
"@

    # Combine all sections
    $fullContent = @"
$header
$envSection
$mcpSectionContent
$launchSection
"@

    return $fullContent
}

