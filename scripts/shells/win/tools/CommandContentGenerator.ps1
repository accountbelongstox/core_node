<#
.SYNOPSIS
    Generate corresponding MCP synchronization section based on tool type

.DESCRIPTION
    Generate corresponding MCP synchronization and pre-launch task content based on different AI tool types

.PARAMETER ToolType
    Tool type ("claude" or "droid")

.EXAMPLE
    $mcpContent = Get-McpSectionByToolType -ToolType "claude"
#>
function Get-McpSectionByToolType {
    param(
        [Parameter(Mandatory=$true)]
        [string]$ToolType
    )
    
    switch ($ToolType.ToLower()) {
        "claude" {
            return New-ClaudeMcpSection
        }
        "droid" {
            return New-DroidMcpSection
        }
        default {
            Write-ColorMessage -Message "Unknown tool type: $ToolType" -Type "Warning"
            return ""
        }
    }
}

<#
.SYNOPSIS
    Generate environment variable setup commands

.DESCRIPTION
    Generate corresponding batch setup commands based on environment variable configuration

.PARAMETER Variables
    Environment variable configuration array

.PARAMETER UserInputs
    User input environment variable values

.EXAMPLE
    $envCommands = New-EnvironmentCommands -Variables $config.Variables -UserInputs $userInputs
#>
function New-EnvironmentCommands {
    param(
        [Parameter(Mandatory=$true)]
        [array]$Variables,
        
        [Parameter(Mandatory=$true)]
        [hashtable]$UserInputs
    )
    
    $envCommands = @()
    $psEnvVars = @()
    
    foreach ($var in $Variables) {
        $userInput = $UserInputs[$var.Name]
        
        if (-not [string]::IsNullOrWhiteSpace($userInput)) {
            # Add batch commands
            $envCommands += "echo Setting $($var.Name)=$userInput"
            $envCommands += "set $($var.Name)=$userInput"
            
            # Add PowerShell environment variables
            $psEnvVars += "`$env:$($var.Name)='$userInput'"
        } else {
            $envCommands += "echo Skipping $($var.Name) (not set)"
            $envCommands += "REM set $($var.Name)=  # Not set"
        }
    }
    
    return @{
        EnvCommands = $envCommands
        PsEnvVars = $psEnvVars -join "; "
    }
}

<#
.SYNOPSIS
    Preview generated command content

.DESCRIPTION
    Display command content preview before generating actual file

.PARAMETER Content
    Content to preview

.PARAMETER FilePath
    Target file path

.EXAMPLE
    Show-CommandPreview -Content $batchContent -FilePath $targetPath
#>
function Show-CommandPreview {
    param(
        [Parameter(Mandatory=$true)]
        [string]$Content,
        
        [Parameter(Mandatory=$true)]
        [string]$FilePath
    )
    
    Write-ColorMessage -Message "`nPreview of generated batch file:" -Type "Info"
    Write-ColorMessage -Message "File path: $FilePath" -Type "Info"
    Write-ColorMessage -Message ("=" * 50) -Type "Info"
    Write-Host $Content -ForegroundColor Cyan
    Write-ColorMessage -Message ("=" * 50) -Type "Info"
}

<#
.SYNOPSIS
    Confirm command generation

.DESCRIPTION
    Ask user whether to confirm command file generation

.PARAMETER None

.EXAMPLE
    $confirmed = Confirm-CommandGeneration
#>
function Confirm-CommandGeneration {
    Write-ColorMessage -Message "Press Enter to generate file, any other key to cancel" -Type "Info"
    $confirm = Read-Host "Confirm"
    
    if ($confirm -ne '') {
        Write-ColorMessage -Message "Command generation cancelled." -Type "Warning"
        return $false
    }
    
    return $true
}

