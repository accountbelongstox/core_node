<#
.SYNOPSIS
    Get tool configuration by tool type

.DESCRIPTION
    Get standardized tool configuration including display name, target name, and upgrade support

.PARAMETER ToolType
    Tool type (e.g., "claude", "droid")

.EXAMPLE
    $config = Get-ToolConfiguration -ToolType "claude"
#>
function Get-ToolConfiguration {
    param(
        [Parameter(Mandatory=$true)]
        [ValidateNotNullOrEmpty()]
        [string]$ToolType
    )

    $toolConfigs = @{
        "claude" = @{
            DisplayName = "Claude Code"
            TargetName = "claude"
            SupportUpgrade = $true
        }
        "droid" = @{
            DisplayName = "Factory AI Droid"
            TargetName = "droid"
            SupportUpgrade = $true
        }
    }

    $normalizedType = $ToolType.ToLower()
    if ($toolConfigs.ContainsKey($normalizedType)) {
        return $toolConfigs[$normalizedType]
    } else {
        Write-Warning "Unknown tool type: ${ToolType}. Using default configuration."
        return @{
            DisplayName = $ToolType
            TargetName = $normalizedType
            SupportUpgrade = $true
        }
    }
}

<#
.SYNOPSIS
    Generate corresponding MCP synchronization section based on tool type

.DESCRIPTION
    Generate corresponding MCP synchronization and pre-launch task content based on different AI tool types

.PARAMETER ToolType
    Tool type ("claude" or "droid")

.PARAMETER FileName
    The batch file name that will be executed

.EXAMPLE
    $mcpContent = Get-McpSectionByToolType -ToolType "claude" -FileName "claude1.bat"
#>
function Get-McpSectionByToolType {
    param(
        [Parameter(Mandatory=$true)]
        [ValidateNotNullOrEmpty()]
        [string]$ToolType,

        [Parameter(Mandatory=$false)]
        [string]$FileName = ""
    )

    try {
        $config = Get-ToolConfiguration -ToolType $ToolType

        return New-GenericMcpSection `
            -ToolType $ToolType.ToLower() `
            -ToolDisplayName $config.DisplayName `
            -TargetName $config.TargetName `
            -SupportUpgrade $config.SupportUpgrade `
            -FileName $FileName
    } catch {
        Write-Error "Failed to generate MCP section for tool type '${ToolType}': $($_.Exception.Message)"
        return ""
    }
}

<#
.SYNOPSIS
    Generate environment variable setup commands

.DESCRIPTION
    Generate corresponding batch setup commands based on environment variable configuration
    Values are read from SecretManager instead of being stored as plaintext in batch files.

    Key naming convention:
    - For "Add Command" operation: {VariableName}_{FileName} (uppercase, without .bat extension)
    - For "Set XXXX Environment Variables" operation: {VariableName}_DEFAULT (uppercase)

.PARAMETER Variables
    Environment variable configuration array

.PARAMETER UserInputs
    User input environment variable values (used as fallback if SecretManager read fails)

.PARAMETER FileName
    Batch file name (without extension) for key naming

.PARAMETER UseSecretManager
    Whether to use SecretManager for reading values (default: true)

.EXAMPLE
    $envCommands = New-EnvironmentCommands -Variables $config.Variables -UserInputs $userInputs -FileName "claude1"
#>
function New-EnvironmentCommands {
    param(
        [Parameter(Mandatory=$true)]
        [array]$Variables,

        [Parameter(Mandatory=$true)]
        [hashtable]$UserInputs,

        [Parameter(Mandatory=$false)]
        [string]$FileName = "",

        [Parameter(Mandatory=$false)]
        [bool]$UseSecretManager = $true
    )

    $envCommands = @()
    $psEnvVars = @()
    $secretManagerAvailable = (Get-Command Get-SecretKey -ErrorAction SilentlyContinue) -ne $null

    $fileNumber = ""
    if (-not [string]::IsNullOrWhiteSpace($FileName)) {
        if ($FileName -match "(\d+)\.bat$") {
            $fileNumber = $matches[1]
        }
    }

    foreach ($var in $Variables) {
        $varValue = $null
        $secretKeyName = ""

        if ($UseSecretManager -and $secretManagerAvailable) {
            if (-not [string]::IsNullOrWhiteSpace($fileNumber)) {
                $secretKeyName = "$($var.Name)_$fileNumber"
            } else {
                $secretKeyName = "$($var.Name)_DEFAULT"
            }

            try {
                $varValue = Get-SecretKey -KeyName $secretKeyName -ErrorAction SilentlyContinue
                if ([string]::IsNullOrWhiteSpace($varValue)) {
                    $varValue = $null
                }
            } catch {
                $varValue = $null
            }
        }

        if ([string]::IsNullOrWhiteSpace($varValue) -and $UserInputs.ContainsKey($var.Name)) {
            $varValue = $UserInputs[$var.Name]
        }

        if (-not [string]::IsNullOrWhiteSpace($varValue)) {
            $envCommands += "echo Setting $($var.Name)=[LOADED FROM SECRET]"
            $envCommands += "set $($var.Name)=$varValue"
            $psEnvVars += "`$env:$($var.Name)='$varValue'"
        } else {
            $envCommands += "echo Skipping $($var.Name) (not set)"
            $envCommands += "REM set $($var.Name)=  # Not set"
        }
    }

    return @{
        EnvCommands = $envCommands
        PsEnvVars = $psEnvVars -join "; "
    }
}

<#
