function New-SSHCommandContent {
    param(
        [Parameter(Mandatory=$true)]
        [string]$ConfigName,

        [Parameter(Mandatory=$true)]
        [int]$FileNumber,

        [Parameter(Mandatory=$true)]
        [hashtable]$UserInputs,

        [Parameter(Mandatory=$false)]
        [string]$FileName = ""
    )

    $scriptParentDir = Split-Path $PSScriptRoot -Parent
    $winCommonDir = Join-Path $scriptParentDir "win_common"
    $absoluteSecretManagerPath = Join-Path $winCommonDir "SecretManager.ps1"

    $sshConnection = ""
    $passwordKeyName = ""

    if ($UserInputs.ContainsKey("SSH_CONNECTION")) {
        $sshConnection = $UserInputs["SSH_CONNECTION"]
    }

    $passwordKeyName = "SSH_PASSWORD_$FileNumber"

