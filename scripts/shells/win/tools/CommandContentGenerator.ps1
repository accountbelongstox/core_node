<#
.SYNOPSIS
    Generate complete command content (advanced interface)

.DESCRIPTION
    This is the main interface for generating command content, integrating all necessary functionality

.PARAMETER Config
    Configuration object

.PARAMETER CommandPrefix
    Command prefix

.PARAMETER PsCommand
    PowerShell command

.PARAMETER FileNumber
    File number

.PARAMETER UserInputs
    User input environment variable values

.PARAMETER ShowPreview
    Whether to show preview (default: true)

.PARAMETER RequireConfirmation
    Whether to require user confirmation (default: true)

.EXAMPLE
    $result = New-CompleteCommandContent -Config $config -CommandPrefix "claude" -PsCommand "claude" -FileNumber 1 -UserInputs $inputs
#>
function New-CompleteCommandContent {
    param(
        [Parameter(Mandatory=$true)]
        [hashtable]$Config,
        
        [Parameter(Mandatory=$true)]
        [string]$CommandPrefix,
        
        [Parameter(Mandatory=$true)]
        [string]$PsCommand,
        
        [Parameter(Mandatory=$true)]
        [int]$FileNumber,
        
        [Parameter(Mandatory=$true)]
        [hashtable]$UserInputs,
        
        [Parameter(Mandatory=$false)]
        [bool]$ShowPreview = $true,
        
        [Parameter(Mandatory=$false)]
        [bool]$RequireConfirmation = $true
    )
    
    try {
        # 1. Generate environment variable commands
        $envResult = New-EnvironmentCommands -Variables $Config.Variables -UserInputs $UserInputs
        
        # 2. Generate MCP synchronization section
        $mcpSection = Get-McpSectionByToolType -ToolType $PsCommand
        
        # 3. Generate complete command content
        $commandContent = New-CommandContent -ConfigName $Config.Title -CommandPrefix $CommandPrefix -PsCommand $PsCommand -FileNumber $FileNumber -EnvCommands $envResult.EnvCommands -PsEnvVars $envResult.PsEnvVars -McpSection $mcpSection
        
        # 4. Show preview (if needed)
        if ($ShowPreview) {
            $targetPath = "D:\programing\core_node_a\.winenvs\${CommandPrefix}${FileNumber}.bat"
            Show-CommandPreview -Content $commandContent -FilePath $targetPath
        }
        
        # 5. User confirmation (if needed)
        if ($RequireConfirmation) {
            $confirmed = Confirm-CommandGeneration
            if (-not $confirmed) {
                return @{
                    Success = $false
                    Message = "User cancelled command generation"
                    Content = $null
                }
            }
        }
        
        return @{
            Success = $true
            Message = "Command content generated successfully"
            Content = $commandContent
            EnvCommands = $envResult.EnvCommands
            PsEnvVars = $envResult.PsEnvVars
            McpSection = $mcpSection
        }
        
    } catch {
        return @{
            Success = $false
            Message = "Error occurred while generating command content: $($_.Exception.Message)"
            Content = $null
        }
    }
}

