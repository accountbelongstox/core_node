<#
.SYNOPSIS
    Generate complete batch command content

.DESCRIPTION
    Generate batch script content including environment variable setup, MCP synchronization, tool startup and other functionality based on configuration information

.PARAMETER ConfigName
    Configuration name (e.g. "Claude AI", "Factory AI Droid")

.PARAMETER CommandPrefix
    Command prefix (e.g. "claude", "droid")

.PARAMETER PsCommand
    PowerShell command (e.g. "claude", "droid")

.PARAMETER FileNumber
    File number (used to generate unique filename)

.PARAMETER EnvCommands
    Environment variable setup command array

.PARAMETER PsEnvVars
    PowerShell environment variable string

.PARAMETER McpSection
    MCP synchronization section content

.EXAMPLE
    $content = New-CommandContent -ConfigName "Claude AI" -CommandPrefix "claude" -PsCommand "claude" -FileNumber 1 -EnvCommands $envCmds -PsEnvVars $psVars -McpSection $mcp
#>
function New-CommandContent {
    param(
        [Parameter(Mandatory=$true)]
        [string]$ConfigName,

        [Parameter(Mandatory=$true)]
        [string]$CommandPrefix,

        [Parameter(Mandatory=$true)]
        [string]$PsCommand,

        [Parameter(Mandatory=$true)]
        [int]$FileNumber,

        [Parameter(Mandatory=$true)]
        [array]$Variables,

        [Parameter(Mandatory=$false)]
        [string]$McpSection = "",

        [Parameter(Mandatory=$false)]
        [string]$FileName = ""
    )

    $scriptDir = Split-Path $PSScriptRoot -Parent
    $winCommonDir = Join-Path $scriptDir "win_common"
    $secretManagerPath = Join-Path $winCommonDir "SecretManager.ps1"

    $header = @"
# ### AI SPECIAL ATTENTION RULES START ###
# When AI/ALL DEVELOPERS sees this prompt, MUST IMMEDIATELY COMPLY WITH THESE RULES:
# 1. Write all code in English only.
# 2. Never execute, create, or modify test code.
# 3. Never create or update documentation (*.md).
# 4. Never write summaries during development or thinking process.
# 5. Declare all variables at the beginning of the file.
# 6. For PowerShell (*.ps1) scripts: Do not append strings directly to variables, Do not use relative paths such as "..\..\"; instead resolve absolute paths using parent path parsing (Split-Path, Join-Path, or Resolve-Path).
# 7. Do not modify these rules.
# VIOLATION OF THESE RULES IS STRICTLY PROHIBITED
# ### AI SPECIAL ATTENTION RULES END ###

<#
.SYNOPSIS
    $ConfigName Global File #$FileNumber

.DESCRIPTION
    This file is automatically generated by Special Software Environment Manager
    Contains environment variable setup, MCP synchronization and tool startup functionality

.NOTES
    - Tool Name: $ConfigName
    - Command Prefix: $CommandPrefix
    - PowerShell Command: $PsCommand
    - File Number: $FileNumber
    - File Name: $FileName
    - Generation Time: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
#>

Set-StrictMode -Version Latest
`$ErrorActionPreference = "Stop"
"@
    
    $fileNameDisplay = ""
    if (-not [string]::IsNullOrWhiteSpace($FileName)) {
        $fileNameDisplay = @"

Write-Host ""
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "Running: $FileName" -ForegroundColor Yellow
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host ""
"@
    }

    $scriptParentDir = Split-Path $PSScriptRoot -Parent
    $winCommonDir = Join-Path $scriptParentDir "win_common"
    $absoluteSecretManagerPath = Join-Path $winCommonDir "SecretManager.ps1"

    $loadSecretManager = @"

#region Load SecretManager
`$secretManagerPath = "$absoluteSecretManagerPath"

if (Test-Path `$secretManagerPath) {
    . `$secretManagerPath
    Write-Host "[INFO] SecretManager loaded successfully" -ForegroundColor Green
} else {
    Write-Host "[WARNING] SecretManager not found at: `$secretManagerPath" -ForegroundColor Yellow
    Write-Host "[WARNING] Environment variables will not be loaded" -ForegroundColor Yellow
}
#endregion

#region Load Environment Variables from SecretManager
Write-Host ""
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "Loading Environment Variables" -ForegroundColor Yellow
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host ""

"@

    $varLoadingCode = ""
    foreach ($var in $Variables) {
        $secretKeyName = "$($var.Name)_$FileNumber"
        $varLoadingCode += @"
`$env:$($var.Name) = Get-SecretKey -KeyName "$secretKeyName"
if (`$env:$($var.Name)) {
    Write-Host "[SUCCESS] Loaded $($var.Name) = `$(`$env:$($var.Name))" -ForegroundColor Green
} else {
    Write-Host "[WARNING] Failed to load $($var.Name)" -ForegroundColor Yellow
}

"@
    }

    $buildCommandCode = @"

#region Build Launch Command Display
`$envVarsParts = @()

"@

    foreach ($var in $Variables) {
        $buildCommandCode += @"
if (`$env:$($var.Name)) {
    `$envVarsParts += "```$env:$($var.Name)='`$(`$env:$($var.Name))'"
}

"@
    }

    $buildCommandCode += @"
`$envVarsCommand = `$envVarsParts -join '; '
if (`$envVarsCommand) {
    `$fullCommandDisplay = "`$envVarsCommand; $PsCommand"
} else {
    `$fullCommandDisplay = "$PsCommand"
}
#endregion

"@

    $envSection = $loadSecretManager + $varLoadingCode + $buildCommandCode

    $mcpSectionContent = ""
    if (-not [string]::IsNullOrWhiteSpace($McpSection)) {
        $mcpSectionContent = @"

#region MCP Server Synchronization
Write-Host ""
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "MCP Server Synchronization" -ForegroundColor Yellow
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host ""

$McpSection
#endregion

"@
    }

    $launchSection = @"

#region Launch Tool
Write-Host ""
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "Press Enter to start $ConfigName..." -ForegroundColor Yellow
Write-Host "============================================================" -ForegroundColor Cyan
`$null = Read-Host "Press Enter to continue"

Write-Host ""
Write-Host "Executing: $PsCommand" -ForegroundColor White
Write-Host ""
Write-Host "PowerShell Command: powershell -NoProfile -ExecutionPolicy Bypass -Command ```"`$fullCommandDisplay```"" -ForegroundColor White
Write-Host ""
Write-Host "Press any key to continue..." -ForegroundColor Yellow
`$null = `$host.UI.RawUI.ReadKey("NoEcho,IncludeKeyDown")
powershell -NoProfile -ExecutionPolicy Bypass -Command `$fullCommandDisplay

Write-Host ""
pause
#endregion
"@

    $fullContent = @"
$header
$fileNameDisplay
$envSection
$mcpSectionContent
$launchSection
"@

    return $fullContent
}

<#
