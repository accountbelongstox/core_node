# Resource Limiter Common Library
# Provides runtime resource limiting capabilities using cgroups and systemd-run
# Based on unified_manager/common/resource_limiter.sh

# Variables declaration
SCRIPT_CURRENT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PARENT_DIR_LEVEL_1="$(dirname "$SCRIPT_CURRENT_DIR")"
PARENT_DIR_LEVEL_2="$(dirname "$PARENT_DIR_LEVEL_1")"

# Source global variables
source "$SCRIPT_CURRENT_DIR/gvar_common.sh"

DEFAULT_CPU_LIMIT="20"
DEFAULT_MEMORY_LIMIT="200M"
TMP_SCRIPT_DIR="${CORE_NODE_DATA_DIR}/dd_scripts"
RESOURCE_METHOD="auto"
AVAILABLE_METHODS=("systemd-run" "ulimit" "cpulimit" "cgroup")

# Function to calculate memory limits based on system memory
calculate_memory_limits_from_common_functions() {
    local total_memory_kb=$(grep MemTotal /proc/meminfo | awk '{print $2}')
    local total_memory_mb=$((total_memory_kb / 1024))
    local total_memory_gb=$((total_memory_mb / 1024))

    if [ "$total_memory_mb" -le 2048 ]; then
        # 2GB or less: use 200M
        DEFAULT_MEMORY_LIMIT="200M"
    elif [ "$total_memory_mb" -le 4096 ]; then
        # 2-4GB: use 300M
        DEFAULT_MEMORY_LIMIT="300M"
    elif [ "$total_memory_mb" -le 8192 ]; then
        # 4-8GB: use 500M
        DEFAULT_MEMORY_LIMIT="500M"
    else
        # >8GB: use 1G
        DEFAULT_MEMORY_LIMIT="1G"
    fi
}

# Function to ensure tmp script directory exists
ensure_tmp_dir_from_common_functions() {
    mkdir -p "$TMP_SCRIPT_DIR"
    chmod 755 "$TMP_SCRIPT_DIR"
}

# Function to detect best resource limiting method
detect_resource_method_from_common_functions() {
    # Check systemd-run (preferred)
    if command -v systemd-run >/dev/null 2>&1; then
        echo "systemd-run"
        return 0
    fi

    # Check cgroup tools
    if command -v cgcreate >/dev/null 2>&1 && command -v cgexec >/dev/null 2>&1; then
        echo "cgroup"
        return 0
    fi

    # Check cpulimit
    if command -v cpulimit >/dev/null 2>&1; then
        echo "cpulimit"
        return 0
    fi

    # Fallback to ulimit
    echo "ulimit"
    return 0
}

# Function to install dependencies for specific method
install_method_dependencies_from_common_functions() {
    local method="$1"

    case "$method" in
        "systemd-run")
            # systemd is usually pre-installed
            if ! command -v systemd-run >/dev/null 2>&1; then
                echo "[INFO] Installing systemd..."
                $USE_SUDO apt-get update -qq && $USE_SUDO apt-get install -y systemd
            fi
            ;;
        "cgroup")
            if ! command -v cgcreate >/dev/null 2>&1; then
                echo "[INFO] Installing cgroup-tools..."
                $USE_SUDO apt-get update -qq && $USE_SUDO apt-get install -y cgroup-tools
            fi
            ;;
        "cpulimit")
            if ! command -v cpulimit >/dev/null 2>&1; then
                echo "[INFO] Installing cpulimit..."
                $USE_SUDO apt-get update -qq && $USE_SUDO apt-get install -y cpulimit
            fi
            ;;
        "ulimit")
            # ulimit is built-in, no installation needed
            ;;
    esac
}

# Function to create temporary script
create_temp_script_from_common_functions() {
    local command="$1"
    local script_name="dd_temp_$(date +%s)_$$.sh"
    local script_path="$TMP_SCRIPT_DIR/$script_name"

    ensure_tmp_dir_from_common_functions

    cat > "$script_path" << EOF
#!/bin/bash
# Temporary script generated by DD.sh resource limiter
# Generated at: $(date)
# Command: $command

cd "$PWD"
$command
EOF

    chmod +x "$script_path"
    echo "$script_path"
}

# Function to run with systemd-run method
run_with_systemd_from_common_functions() {
    local cpu_limit="$1"
    local memory_limit="$2"
    local script_path="$3"

    echo "[INFO] Using systemd-run method"
    systemd-run --scope --user \
        --property="MemoryMax=$memory_limit" \
        --property="CPUQuota=${cpu_limit}%" \
        "$script_path"
}

# Function to run with ulimit method
run_with_ulimit_from_common_functions() {
    local cpu_limit="$1"
    local memory_limit="$2"
    local script_path="$3"

    echo "[INFO] Using ulimit method"
    # Convert memory to KB for ulimit
    local memory_kb
    case "${memory_limit: -1}" in
        "M"|"m") memory_kb=$((${memory_limit%?} * 1024)) ;;
        "G"|"g") memory_kb=$((${memory_limit%?} * 1024 * 1024)) ;;
        "K"|"k") memory_kb=${memory_limit%?} ;;
        *) memory_kb=$((memory_limit / 1024)) ;;
    esac

    (ulimit -v "$memory_kb"; "$script_path")
}

# Function to run with cpulimit method
run_with_cpulimit_from_common_functions() {
    local cpu_limit="$1"
    local memory_limit="$2"
    local script_path="$3"

    echo "[INFO] Using cpulimit method"
    # Convert memory to KB for ulimit
    local memory_kb
    case "${memory_limit: -1}" in
        "M"|"m") memory_kb=$((${memory_limit%?} * 1024)) ;;
        "G"|"g") memory_kb=$((${memory_limit%?} * 1024 * 1024)) ;;
        "K"|"k") memory_kb=${memory_limit%?} ;;
        *) memory_kb=$((memory_limit / 1024)) ;;
    esac

    (ulimit -v "$memory_kb"; cpulimit -l "$cpu_limit" -- "$script_path")
}

# Function to run with cgroup method
run_with_cgroup_from_common_functions() {
    local cpu_limit="$1"
    local memory_limit="$2"
    local script_path="$3"
    local group_name="dd_limit_$$"

    echo "[INFO] Using cgroup method"

    # Create cgroup
    $USE_SUDO cgcreate -g memory,cpu:/"$group_name"

    # Set memory limit
    echo "$memory_limit" | $USE_SUDO tee /sys/fs/cgroup/memory/"$group_name"/memory.limit_in_bytes >/dev/null

    # Set CPU limit (convert percentage to quota)
    local cpu_quota=$((cpu_limit * 1000))
    echo "$cpu_quota" | $USE_SUDO tee /sys/fs/cgroup/cpu/"$group_name"/cpu.cfs_quota_us >/dev/null
    echo "100000" | $USE_SUDO tee /sys/fs/cgroup/cpu/"$group_name"/cpu.cfs_period_us >/dev/null

    # Execute command
    $USE_SUDO cgexec -g memory,cpu:"$group_name" "$script_path"
    local exit_code=$?

    # Cleanup cgroup
    $USE_SUDO cgdelete -g memory,cpu:"$group_name" 2>/dev/null

    return $exit_code
}

# Main function to run command with resource limits
run_with_limits_from_common_functions() {
    # Calculate memory limits based on system resources
    calculate_memory_limits_from_common_functions

    local cpu_limit="${1:-$DEFAULT_CPU_LIMIT}"
    local memory_limit="${2:-$DEFAULT_MEMORY_LIMIT}"
    local command="$3"
    local method="${4:-auto}"

    if [ -z "$command" ]; then
        echo "[ERROR] Command is required"
        return 1
    fi

    # Auto-detect method if not specified
    if [ "$method" = "auto" ]; then
        method=$(detect_resource_method_from_common_functions)
    fi

    echo "[INFO] Resource limiting method: $method"
    echo "[INFO] CPU Limit: ${cpu_limit}%"
    echo "[INFO] Memory Limit: $memory_limit"
    echo "[INFO] Command: $command"

    # Install dependencies for the chosen method
    install_method_dependencies_from_common_functions "$method"

    # Create temporary script
    local script_path=$(create_temp_script_from_common_functions "$command")
    echo "[INFO] Temporary script: $script_path"
    echo ""

    # Execute with the chosen method
    local exit_code=0
    case "$method" in
        "systemd-run")
            run_with_systemd_from_common_functions "$cpu_limit" "$memory_limit" "$script_path"
            exit_code=$?
            ;;
        "ulimit")
            run_with_ulimit_from_common_functions "$cpu_limit" "$memory_limit" "$script_path"
            exit_code=$?
            ;;
        "cpulimit")
            run_with_cpulimit_from_common_functions "$cpu_limit" "$memory_limit" "$script_path"
            exit_code=$?
            ;;
        "cgroup")
            run_with_cgroup_from_common_functions "$cpu_limit" "$memory_limit" "$script_path"
            exit_code=$?
            ;;
        *)
            echo "[ERROR] Unknown method: $method"
            exit_code=1
            ;;
    esac

    # Cleanup temporary script
    rm -f "$script_path"

    if [ $exit_code -eq 0 ]; then
        echo "[SUCCESS] Command completed successfully"
    else
        echo "[ERROR] Command failed with exit code: $exit_code"
    fi

    return $exit_code
}

# Function to run command in background with resource limits
run_with_limits_background_from_common_functions() {
    # Calculate memory limits based on system resources
    calculate_memory_limits_from_common_functions

    local cpu_limit="${1:-$DEFAULT_CPU_LIMIT}"
    local memory_limit="${2:-$DEFAULT_MEMORY_LIMIT}"
    local command="$3"
    local method="${4:-auto}"
    local log_file="${5:-${CORE_NODE_DATA_DIR}/dd-bg-$(date +%s).log}"

    if [ -z "$command" ]; then
        echo "[ERROR] Command is required"
        return 1
    fi

    # Auto-detect method if not specified
    if [ "$method" = "auto" ]; then
        method=$(detect_resource_method_from_common_functions)
    fi

    echo "[INFO] Background resource limiting method: $method"
    echo "[INFO] CPU Limit: ${cpu_limit}%"
    echo "[INFO] Memory Limit: $memory_limit"
    echo "[INFO] Command: $command"
    echo "[INFO] Log file: $log_file"

    # Install dependencies for the chosen method
    install_method_dependencies_from_common_functions "$method"

    # Create temporary script
    local script_path=$(create_temp_script_from_common_functions "$command")
    echo "[INFO] Temporary script: $script_path"
    echo ""

    # Execute in background with the chosen method
    case "$method" in
        "systemd-run")
            nohup systemd-run --scope --user \
                --property="MemoryMax=$memory_limit" \
                --property="CPUQuota=${cpu_limit}%" \
                "$script_path" > "$log_file" 2>&1 &
            ;;
        "cpulimit")
            local memory_kb
            case "${memory_limit: -1}" in
                "M"|"m") memory_kb=$((${memory_limit%?} * 1024)) ;;
                "G"|"g") memory_kb=$((${memory_limit%?} * 1024 * 1024)) ;;
                "K"|"k") memory_kb=${memory_limit%?} ;;
                *) memory_kb=$((memory_limit / 1024)) ;;
            esac
            nohup bash -c "ulimit -v $memory_kb; cpulimit -l $cpu_limit -- $script_path" > "$log_file" 2>&1 &
            ;;
        *)
            local memory_kb
            case "${memory_limit: -1}" in
                "M"|"m") memory_kb=$((${memory_limit%?} * 1024)) ;;
                "G"|"g") memory_kb=$((${memory_limit%?} * 1024 * 1024)) ;;
                "K"|"k") memory_kb=${memory_limit%?} ;;
                *) memory_kb=$((memory_limit / 1024)) ;;
            esac
            nohup bash -c "ulimit -v $memory_kb; $script_path" > "$log_file" 2>&1 &
            ;;
    esac

    local bg_pid=$!
    echo "[SUCCESS] Background command started successfully"
    echo "[INFO] Process ID: $bg_pid"
    echo "[INFO] Log file: $log_file"
    echo "[INFO] Temporary script: $script_path (will be cleaned up when process ends)"

    return 0
}

# Function to create systemd service with resource limits
create_systemd_service_with_limits_from_common_functions() {
    local service_name="$1"
    local command="$2"
    local working_dir="$3"
    local cpu_limit="${4:-$DEFAULT_CPU_LIMIT}"
    local memory_limit="${5:-$DEFAULT_MEMORY_LIMIT}"
    local description="${6:-Service with resource limits}"

    # Calculate memory limits based on system resources
    calculate_memory_limits_from_common_functions

    # Use calculated limits if defaults are provided
    if [ "$cpu_limit" = "$DEFAULT_CPU_LIMIT" ]; then
        cpu_limit="$DEFAULT_CPU_LIMIT"
    fi
    if [ "$memory_limit" = "$DEFAULT_MEMORY_LIMIT" ]; then
        memory_limit="$DEFAULT_MEMORY_LIMIT"
    fi

    echo "[INFO] Creating systemd service: $service_name"
    echo "[INFO] Command: $command"
    echo "[INFO] Working directory: $working_dir"
    echo "[INFO] CPU limit: ${cpu_limit}%"
    echo "[INFO] Memory limit: $memory_limit"

    # Calculate memory high (80% of max for soft limit)
    local memory_high
    case "${memory_limit: -1}" in
        "M"|"m") memory_high="$((${memory_limit%?} * 80 / 100))M" ;;
        "G"|"g") memory_high="$((${memory_limit%?} * 80 / 100))G" ;;
        "K"|"k") memory_high="$((${memory_limit%?} * 80 / 100))K" ;;
        *) memory_high="$((memory_limit * 80 / 100))" ;;
    esac

    # Create service file
    $USE_SUDO tee "/etc/systemd/system/${service_name}.service" > /dev/null << EOF
[Unit]
Description=$description
After=network.target

[Service]
Type=simple
User=$USER
WorkingDirectory=$working_dir
ExecStart=$command
Restart=always
RestartSec=10
CPUQuota=${cpu_limit}%
MemoryMax=$memory_limit
MemoryHigh=$memory_high
TasksMax=100
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
EOF

    # Reload systemd and enable service
    $USE_SUDO systemctl daemon-reload
    $USE_SUDO systemctl enable "$service_name.service"

    echo "[SUCCESS] Systemd service created and enabled: $service_name.service"
    return 0
}
